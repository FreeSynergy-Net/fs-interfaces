//! Which conformance rules must break for each `Fault`: an exhaustive match, so a new fault without a rule does not compile.
//!
//! Pattern: Registry by exhaustive match. A name is a rule of `run` or a prefix of the matrix rules (`matrix:<op>`).

use super::state::Fault;

/// The rules of which at least one must fail when `fault` is switched on.
#[must_use]
#[allow(clippy::match_same_arms)]
pub fn rules_for(fault: Fault) -> &'static [&'static str] {
    match fault {
        Fault::IgnoreRights => &["rights.stranger.read", "matrix:stat"],
        Fault::SkipNameCheck => &["names.bad"],
        Fault::FollowLinks => &["link.never-followed", "matrix:list"],
        Fault::WrongSha => &["file.sha256"],
        Fault::Replace => &["conflict.never-replace"],
        Fault::PurgeOnTrash => &["trash.restore-purge", "matrix:trash"],
        Fault::TrashLeak => &["rights.trash.private", "matrix:list"],
        Fault::NoCancel => &["write.cancel"],
        Fault::BotAllowed => &["rights.bot", "matrix:stat"],
        Fault::AdminReadsAll => &["rights.manager.no-server", "matrix:open"],
        Fault::OperatorBlocked => &["rights.operator.reads-all", "matrix:stat"],
        Fault::OperatorChanges => &["rights.operator.reads-all", "matrix:rename"],
        Fault::ManagerChanges => &["rights.manager.no-server", "matrix:rename"],
        Fault::MoveIgnoresTarget => &["matrix:move_dst"],
        Fault::CopyIgnoresTarget => &["matrix:copy_dst"],
        Fault::RestoreIgnoresTarget => &["matrix:restore_dst"],
        Fault::MemberWritesGroup => &["matrix:write", "matrix:rename"],
        Fault::RestoreNotOwner => &["matrix:restore_src"],
        Fault::RootMutable => &["matrix:rename", "matrix:trash"],
        Fault::WriteIntoTrash => &["matrix:write"],
        Fault::WriteBelowTrashed => &["matrix:write:T8B"],
        Fault::NoCycle => &["matrix:move_cycle", "matrix:copy_cycle"],
        Fault::ValidityBeforeRights => &["matrix:create_file"],
        Fault::BodyBeforeRights => &["matrix:write_cancelled"],
        Fault::BotTrash => &["matrix:stat:T7", "matrix:list:T7"],
        Fault::NoUsage => &["rights.manager.no-server"],
        Fault::CapsLie => &["caps.honest"],
        Fault::ChangesLeak => &["changes.delta"],
        Fault::ScopeTrash => &["scope.generator"],
        Fault::BlobEntryWrong => &["blob.range"],
        Fault::OpenTrashLeak => &["matrix:open"],
        Fault::StatTrashLeak => &["matrix:stat"],
        Fault::FollowLinksOpen => &["matrix:open:T11"],
        Fault::FollowLinksWrite => &["matrix:write:T11"],
        Fault::CopyFollowsLink => &["link.never-followed"],
        Fault::DeleteFollowsLink => &["link.never-followed"],
        Fault::RenameReplaces => &["conflict.rename"],
        Fault::NoOperatorLog => &["operator.log"],
        Fault::ManagerGroupRoot => &["matrix:write", "rights.manager.no-server"],
        Fault::OperatorRoot => &["matrix:write", "rights.operator.reads-all"],
        Fault::OperatorLink => &["matrix:rename", "rights.operator.reads-all"],
        Fault::NoReadCap | Fault::ZeroRead | Fault::ReadsTooMuch | Fault::BadRange => {
            &["blob.range"]
        }
        Fault::PathTraversal => &["path.traversal"],
        Fault::ScopeLeak => &["scope.generator"],
    }
}

